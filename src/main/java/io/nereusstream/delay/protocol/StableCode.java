package io.nereusstream.delay.protocol;

/** Closed V1 result codes used by the command state machine. */
public enum StableCode {
    OK(0x0000),
    INVALID_COMMAND(0x0101),
    INVALID_PREPARED_COMMAND(0x0102),
    PREPARED_COMMAND_EXPIRED(0x0107),
    SDK_BACKPRESSURE_NOT_SUBMITTED(0x0201),
    BROKER_DEFINITIVE_NOT_PERSISTED(0x0202),
    ENQUEUE_RESULT_UNCERTAIN(0x0203),
    SCHEDULED(0x1001),
    CANCELED(0x1002),
    SUPERSEDED(0x1003),
    NOT_FOUND(0x1004),
    TOO_LATE(0x1005),
    ALREADY_PUBLISHED(0x1006),
    ALREADY_CANCELED(0x1007),
    VERSION_CONFLICT(0x1008),
    INVALID_DELIVERY_WINDOW(0x1101),
    UNAUTHORIZED(0x1102),
    HARD_QUOTA_EXCEEDED(0x1104),
    ROUTE_NOT_ACTIVE(0x1105),
    COMMAND_ID_CONFLICT(0x1106),
    COMMAND_RETRY_WINDOW_EXPIRED(0x1107),
    DELAY_MESSAGE_ID_CONFLICT(0x1108),
    LANE_TERMINALLY_CLOSED(0x110e),
    PROFILE_VERSION_NOT_ACTIVE_AT_SOURCE_POSITION(0x110b),
    LANE_CLOSED(0x110d),
    UNACTIVATED_PROTOCOL_VERSION(0x2001),
    QUARANTINED_SOURCE_RECORD(0x2007),
    INVALID_RECEIPT(0x3001),
    SHARD_TRANSITIONING(0x3006),
    SHARD_UNAVAILABLE(0x3007),
    INTEGRITY_ERROR(0x3008),
    RESOURCE_INCARNATION_MISMATCH(0x5002),
    SOURCE_GAP(0x6001);

    private final int wireValue;

    StableCode(final int wireValue) {
        this.wireValue = wireValue;
    }

    public int wireValue() {
        return wireValue;
    }
}
