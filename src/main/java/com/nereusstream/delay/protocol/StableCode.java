    StableCode(final int wireValue) {
        this.wireValue = wireValue;
    }

    public int wireValue() {
        return wireValue;
    }

    public static StableCode fromWire(final int value) {
        for (StableCode code : values()) {
            if (code.wireValue == value) {
                return code;
            }
        }
        throw new IllegalArgumentException("unknown StableCode wire value: " + value);
    }
